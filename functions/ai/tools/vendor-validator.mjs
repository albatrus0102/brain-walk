#!/usr/bin/env node
/**
 * Bundle the pure validator (functions/ai/core + data) into ONE dependency-free CommonJS file for the
 * routine repo: brain-walk-ai/tools/bw-validator.cjs. The routine's `bw-io.mjs check` runs the exact
 * same checks as the server (minus the database-backed dedupe/quota).
 *
 *   node functions/ai/tools/vendor-validator.mjs <out-file>
 *
 * The header carries the core VERSION and a sha256 of the bundled sources. bw-io prints both, and the
 * server's aiRead(bankNeeds) returns `validator: {version, sha}` so a stale copy is visible.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';

const here = path.dirname(new URL(import.meta.url).pathname);
const root = path.resolve(here, '..');
const MODS = ['core/text.js', 'core/lexicon.js', 'core/kdate.js', 'core/checks.js', 'core/formats.js', 'core/item.js', 'core/report.js', 'core/template.js', 'core/index.js'];
const DATA = ['data/words.json', 'data/relations.json', 'data/items.json', 'data/emoji.json', 'data/banned.json', 'data/names.json', 'data/donotcopy.json', 'data/holidays-2026-2030.json'];

export function build() {
  const parts = [];
  for (const f of DATA) parts.push(`  ${JSON.stringify(f)}: function (module) { module.exports = ${fs.readFileSync(path.join(root, f), 'utf8').trim()}; },`);
  for (const f of MODS) parts.push(`  ${JSON.stringify(f)}: function (module, exports, require) {\n${fs.readFileSync(path.join(root, f), 'utf8')}\n  },`);
  const body = parts.join('\n');
  const sha = crypto.createHash('sha256').update(body).digest('hex');
  const version = createRequire(import.meta.url)(path.join(root, 'core/index.js')).VERSION;
  const out = `// bw-validator ${version} sha256:${sha}
// GENERATED by brain-walk functions/ai/tools/vendor-validator.mjs — do not edit. Re-vendor when the server changes.
'use strict';
const __defs = {
${body}
};
const __cache = {};
function __resolve(from, req) {
  if (req.startsWith('node:')) return req;
  const base = from.split('/').slice(0, -1);
  for (const seg of req.split('/')) { if (seg === '..') base.pop(); else if (seg !== '.') base.push(seg); }
  return base.join('/');
}
function __load(id) {
  if (__cache[id]) return __cache[id].exports;
  if (!__defs[id]) return require(id);
  const module = { exports: {} }; __cache[id] = module;
  __defs[id](module, module.exports, (r) => __load(__resolve(id, r)));
  return module.exports;
}
module.exports = Object.assign({}, __load('core/index.js'), { SOURCE_SHA: ${JSON.stringify(sha)} });
`;
  return { out, sha, version };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const target = process.argv[2];
  if (!target) { console.error('usage: vendor-validator.mjs <out-file>'); process.exit(2); }
  const { out, sha, version } = build();
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, out);
  console.log(`wrote ${target} (v${version}, sha256:${sha.slice(0, 12)}…)`);
}
