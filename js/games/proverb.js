const CATMAP = Object.fromEntries(CATS.map(c => [c[0], c]));
const NEAR = { '과일': ['채소'], '채소': ['과일', '곡식'], '곡식': ['채소'], '나라': ['도시'], '도시': ['나라'], '가구': ['가전제품'], '가전제품': ['가구', '주방도구'], '주방도구': ['가전제품'] };
function catQuestion(level) {
  const nC = level === 1 ? 3 : 4;
  const cat = pick(CATS, 1)[0];
  const outsiderCats = () => CATS.filter(c => c[0] !== cat[0] && c[1] !== cat[1]);
  const positive = level >= 3 && Math.random() < 0.4;
  if (!positive) {
    let outCat;
    if (level >= 4 && NEAR[cat[0]] && Math.random() < 0.6) outCat = CATMAP[pick(NEAR[cat[0]], 1)[0]];
    else outCat = pick(outsiderCats(), 1)[0];
    const odd = pick(outCat[2], 1)[0];
    const members = pick(cat[2], nC - 1);
    return { q: '다음 중 ‘' + cat[0] + '’이(가) 아닌 것을 골라 주세요.', ans: odd, choices: shuffle(members.concat([odd])), info: cat[0] + ': ' + members.slice(0, 3).join(', ') };
  }
  const ans = pick(cat[2], 1)[0];
  const others = pick(outsiderCats(), 12), seenCat = new Set(), outs = [];
  for (const oc of others) { if (outs.length >= nC - 1) break; if (seenCat.has(oc[0])) continue; seenCat.add(oc[0]); outs.push(pick(oc[2], 1)[0]); }
  return { q: '다음 중 ‘' + cat[0] + '’에 해당하는 것을 골라 주세요.', ans, choices: shuffle(outs.concat([ans])), info: ans + '은(는) ' + cat[0] + '이에요.' };
}
reg({
  id: 'proverb', name: '속담·단어 잇기', domain: 'orientation', desc: '속담을 완성하고 낱말을 떠올려요', rounds: 5,
  play(ctx) {
    if (!ctx.mem.plan) { ctx.mem.plan = shuffle(['p', 'p', 'p', 'c', 'c']); ctx.mem.pv = shuffle(PROVERBS.map((_, i) => i)); }
    const typ = ctx.mem.plan[ctx.round];
    const lv = ctx.level, nC = lv === 1 ? 3 : 4;
    if (typ === 'p') {
      const p = PROVERBS[ctx.mem.pv.pop()], rev = lv >= 3 && (lv >= 4 || Math.random() < 0.5), ix = rev ? 1 : 0;
      const given = p[ix === 0 ? 0 : 1], ans = p[ix === 0 ? 1 : 0];
      const pool = PROVERBS.map(x => x[ix === 0 ? 1 : 0]).filter(x => x !== ans);
      const choices = dedupe(ans, pick(pool, 6), nC);
      const full = p[0] + ' ' + p[1];
      const q = '속담을 완성해 주세요.';
      const blank = rev ? '( ? ) ' + given : given + ' ( ? )';
      ctx.prompt(q + ' ' + blank, rev ? '속담을 완성해 주세요. 빈칸 뒤에 이어지는 말은 ' + given + ' 입니다.' : '속담을 완성해 주세요. ' + given + ', 무엇일까요?');
      ctx.mc({ pre: '<div class="card filled center t-headline">' + esc(blank) + '</div>', choices, answer: ans, speakChoices: true,
        right: '맞아요! ‘' + full + '’', wrong: '괜찮아요. 속담은 이렇게 이어져요: ‘' + full + '’' });
    } else {
      const c = catQuestion(lv);
      ctx.prompt(c.q);
      ctx.mc({ choices: c.choices, answer: c.ans, speakChoices: true, right: '맞아요! 정답은 ‘' + c.ans + '’입니다.', wrong: '괜찮아요. 정답은 ‘' + c.ans + '’입니다. ' + c.info });
    }
  }
});

