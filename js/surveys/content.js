/* 점수 → 참고 기준 안내 (중립 문구, 빨강 없음) */
export function bandOf(sv, score) {
  if (!sv.ref) return { key: 'none', text: '', note: '' };
  const r = sv.ref;
  if (score >= r.cut) return { key: 'above', text: '참고 기준(' + r.label + ') 이상', note: r.note };
  if (r.cutMild != null && score >= r.cutMild) return { key: 'mild', text: '경도 포함 참고 기준(' + r.cutMild + '점 이상)', note: r.note };
  return { key: 'below', text: '참고 기준(' + r.label + ') 미만', note: r.note };
}
